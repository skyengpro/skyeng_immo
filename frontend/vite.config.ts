import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, URL } from 'node:url';
import { defineConfig, loadEnv, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';

// The app is served by the Frappe site at /sky-immo (skyeng_immo/www/sky-immo/index.html),
// its files from /assets/skyeng_immo/sky-immo/ (skyeng_immo/public/sky-immo).
const OUT_DIR = fileURLToPath(new URL('../skyeng_immo/public/sky-immo', import.meta.url));
const WWW_PAGE = fileURLToPath(new URL('../skyeng_immo/www/sky-immo/index.html', import.meta.url));

/** Copies the built index.html to the www page. no-cache: a rebuild changes the asset hashes. */
function frappePage(): Plugin {
  return {
    name: 'sky-immo-frappe-page',
    apply: 'build',
    closeBundle() {
      const html = readFileSync(`${OUT_DIR}/index.html`, 'utf8');
      mkdirSync(fileURLToPath(new URL('../skyeng_immo/www/sky-immo', import.meta.url)), { recursive: true });
      const marker = '<!-- no-cache -->\n<!-- Generated by frontend/vite.config.ts from frontend/index.html: do not edit. -->';
      writeFileSync(WWW_PAGE, html.replace(/^(<!doctype html>)/i, `$1\n${marker}`));
    },
  };
}

export default defineConfig(({ command, mode }) => {
  const env = loadEnv(mode, process.cwd(), '');
  // Dev server: API calls go to the bench. FRAPPE_SITE picks the site on a multi-site bench.
  const target = env.FRAPPE_URL || 'http://127.0.0.1:8001';
  const site = env.FRAPPE_SITE || 'immo.localhost';

  return {
    base: command === 'build' ? '/assets/skyeng_immo/sky-immo/' : '/',
    server: {
      port: 8080,
      proxy: {
        '^/(api|files|private|update-password|login)': { target, headers: { Host: site } },
        '^/assets/(?!skyeng_immo/sky-immo)': { target, headers: { Host: site } },
      },
    },
    build: {
      outDir: OUT_DIR,
      emptyOutDir: true,
      rollupOptions: {
        output: {
          manualChunks: {
            react: ['react', 'react-dom', 'react-router'],
            i18n: ['i18next', 'react-i18next'],
          },
        },
      },
    },
    resolve: {
      alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
    },
    plugins: [react(), frappePage()],
  };
});
